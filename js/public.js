// Открытая таблица для зрителей (решение автора 2026-11-14: «делаем, все гости, всё, как у ведущего»).
// Раньше имена и баллы гостей жили только в закрытой базе. Теперь панель ведущего кладёт готовую
// таблицу в отдельный документ public/table, а страница tablica/ показывает его без входа.
// Зритель видит только эту таблицу: вопросы, выпуски и журналы для него закрыты правилами базы.
// Таблица лежит одной строкой JSON: так панель точно знает, поменялась ли она, и не пишет зря.
// Чтение без входа открывают новые правила базы (firestore.rules): пока они не опубликованы,
// страница пишет «Таблица скоро откроется».
import { db, doc, setDoc } from './fb.js';
import { publicTable } from './season.js';

let timer = null;

// Зовётся после каждой перемены выпусков, участников и сезона. Пишет не чаще раза в 1,5 секунды
// и только когда всё прочитано из базы: пустая панель при запуске таблицу не стирает
export function publish(S) {
  clearTimeout(timer);
  timer = setTimeout(() => {
    const s = S.seen;
    if (!s.sums || !s.players || !s.season || !s.pub) return;
    const json = JSON.stringify(publicTable(S.episodes, S.players, S.season));
    if (json === S.pub) return;
    S.pub = json;
    setDoc(doc(db, 'public', 'table'), { json, at: Date.now() }).catch(() => { S.pub = ''; });
  }, 1500);
}
